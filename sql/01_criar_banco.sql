-- PostgreSQL. O Python cria o banco; este arquivo cria somente cinco tabelas.
CREATE TABLE dim_orgao (
 sk_orgao INTEGER PRIMARY KEY, cnpj_orgao VARCHAR(30) NOT NULL UNIQUE,
 nome_orgao TEXT NOT NULL, poder VARCHAR(30) NOT NULL
);
CREATE TABLE dim_fornecedor (
 sk_fornecedor INTEGER PRIMARY KEY, ni_fornecedor VARCHAR(80) NOT NULL UNIQUE,
 nome_fornecedor TEXT, tipo_pessoa VARCHAR(30), porte VARCHAR(100)
);
CREATE TABLE dim_modalidade (
 sk_modalidade INTEGER PRIMARY KEY, modalidade_id INTEGER NOT NULL UNIQUE,
 nome_modalidade VARCHAR(80) NOT NULL
);
CREATE TABLE dim_localidade (
 sk_localidade INTEGER PRIMARY KEY, uf_sigla VARCHAR(30) NOT NULL UNIQUE,
 uf_nome VARCHAR(60) NOT NULL, regiao VARCHAR(30) NOT NULL
);
CREATE TABLE fato_item_contratado (
 sk_fato BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 numero_controle_pncp VARCHAR(60) NOT NULL, numero_item INTEGER NOT NULL,
 sk_orgao INTEGER NOT NULL REFERENCES dim_orgao(sk_orgao),
 sk_fornecedor INTEGER NOT NULL REFERENCES dim_fornecedor(sk_fornecedor),
 sk_modalidade INTEGER NOT NULL REFERENCES dim_modalidade(sk_modalidade),
 sk_localidade INTEGER NOT NULL REFERENCES dim_localidade(sk_localidade),
 data_publicacao DATE NOT NULL, data_homologacao DATE,
 descricao_item TEXT, perfil_gasto VARCHAR(30) NOT NULL CHECK (perfil_gasto IN ('Bens','Serviços','Obras e engenharia')),
 quantidade DECIMAL(18,4) NOT NULL CHECK (quantidade > 0),
 valor_unitario_estimado DECIMAL(18,4) NOT NULL CHECK (valor_unitario_estimado > 0),
 valor_total_estimado DECIMAL(18,2) NOT NULL CHECK (valor_total_estimado >= 1 AND valor_total_estimado <= 1000000000000),
 valor_unitario_homologado DECIMAL(18,4) NOT NULL CHECK (valor_unitario_homologado > 0),
 valor_total_homologado DECIMAL(18,2) NOT NULL CHECK (valor_total_homologado >= 0 AND valor_total_homologado <= 1000000000000),
 comparavel SMALLINT NOT NULL CHECK (comparavel IN (0,1)),
 economia_valor DECIMAL(18,2), dias_ciclo INTEGER CHECK (dias_ciclo >= 0),
 UNIQUE (numero_controle_pncp, numero_item),
 CHECK (data_homologacao IS NULL OR data_homologacao >= data_publicacao),
 CHECK ((data_homologacao IS NULL AND dias_ciclo IS NULL) OR
        (data_homologacao IS NOT NULL AND dias_ciclo IS NOT NULL AND dias_ciclo = data_homologacao - data_publicacao)),
 CHECK ((comparavel = 0 AND economia_valor IS NULL) OR
        (comparavel = 1 AND economia_valor IS NOT NULL AND economia_valor = valor_total_estimado - valor_total_homologado))
);
-- Economia pode ser negativa: sobrepreco e um resultado analitico valido.
